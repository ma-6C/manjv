def api_for(jid, config, index=0, start=1, seconds=5):
    job = {'id': jid, 'kind': 'transform_preview', 'status': 'running', 'ids': [p['id']],
           'cancel': threading.Event(), 'processes': set(), 'created': time.time(), 'config': copy.deepcopy(config),
           'options': {'videoIndex': index, 'start': start, 'seconds': seconds}, 'checkpoints': {}, 'completedStages': []}
    s.JOBS[jid] = job
    counters = {'before': 0, 'after': 0, 'metric': 0}

    def ff(args, job_id):
        counters['before'] += 1
        return s.ff(args, job_id)

    def encode(args, job_id):
        counters['after'] += 1
        return s.encode_media(args, job_id)

    def run(args, *args2, **kwargs):
        if '-filter_complex' in args:
            counters['metric'] += 1
        return s.run_process(args, *args2, **kwargs)

    def stage(job_id, label, progress):
        if s.JOBS[job_id]['cancel'].is_set():
            raise InterruptedError('controlled preview cancellation')
        s.JOBS[job_id].update(stage=label, progress=progress)

    api = SimpleNamespace(FFMPEG=s.FFMPEG, JOBS=s.JOBS, probe=s.probe, project_dir=s.project_dir,
                          register=s.register, checkpoint=s.checkpoint, cached=s.cached,
                          persist_jobs=s.persist_jobs, filters=s.filters, encoder=s.encoder,
                          ff=ff, encode_media=encode, run_process=run, stage=stage)
    return api, job, counters


