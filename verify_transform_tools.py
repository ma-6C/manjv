def check(name, condition=True):
    assert condition, name
    checks.append(name)


def rejects(name, callback):
    try:
        callback()
    except ValueError:
        check(name)
    else:
        raise AssertionError(name)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


