// Local application acceptance test; uses an isolated data directory/server.
const { chromium } = require('C:/Users/yumda/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
 const output=path.resolve('tmp/ui-check');fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8766');await page.locator('#content h1').waitFor();
 const pages=['scan','preprocess','transform','parallel','subtitle','cost','api','text','highlight','publish','logs'];
 const results=[];
 for(const id of pages){
  await page.locator(`#nav a[href="#${id}"]`).click();
  await page.waitForFunction(id=>location.hash==='#'+id,id);
  await page.locator('#content h1').waitFor();
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  if(overflow)throw new Error('Horizontal overflow: '+id);
  results.push({page:id,title:await page.locator('#content h1').textContent(),rendered:true});
 }
 await page.locator('#nav a[href="#scan"]').click();
 const latest=fs.readdirSync('tmp/acceptance').sort().at(-1);
 await page.locator('#config-source').fill(path.resolve('tmp/acceptance',latest,'素材'));
 await page.locator('#config-output').fill(path.resolve('tmp/ui-check/output'));
 await page.locator('[data-action="scan"]').click();
 await page.getByRole('button',{name:'预览',exact:true}).waitFor();
 await page.locator('#nav a[href="#preprocess"]').click();
 await page.locator('#config-width').fill('320');await page.locator('#config-width').press('Tab');
 await page.waitForTimeout(200);
 await page.locator('#config-height').fill('568');await page.locator('#config-height').press('Tab');
 await page.waitForTimeout(200);
 await page.locator('#config-segmentSeconds').fill('1');await page.locator('#config-segmentSeconds').press('Tab');
 await page.waitForTimeout(250);
 await page.locator('#nav a[href="#api"]').click();
 await page.locator('[data-config="autoCover"]').check();
 await page.waitForTimeout(200);
 await page.locator('#start-pipeline').click();
 await page.waitForFunction(async()=>{const s=await(await fetch('/api/state')).json();return s.jobs.at(-1)?.status==='completed';},{},{timeout:60000});
 await page.locator('#nav a[href="#scan"]').click();
 await page.getByText('已处理',{exact:true}).waitFor();
 await page.getByRole('button',{name:'预览',exact:true}).click();
 await page.locator('#project-dialog').waitFor({state:'visible'});
 await page.locator('#detail-video').evaluate(el=>el.play());
 await page.waitForFunction(()=>document.querySelector('#detail-video').currentTime>0);
 await page.locator('[data-action="close-detail"]').click();
 await page.screenshot({path:path.join(output,'desktop-layout.png'),fullPage:true});
 await page.locator('#nav a[href="#text"]').click();
 await page.locator('.cover-preview img').waitFor();
 await page.screenshot({path:path.join(output,'text-cover-layout.png'),fullPage:true});
 await page.locator('#nav a[href="#publish"]').click();
 await page.locator('#account-name').fill('本地验收账号（未登录）');
 await page.locator('[data-action="account-add"]').click();
 await page.getByText('本地验收账号（未登录）',{exact:true}).first().waitFor();
 await page.locator('#publish-rights').check();
 await page.locator('[data-publish-account]').check();
 await page.locator('[data-action="upload-review"]').click();
 await page.locator('#upload-dialog').waitFor({state:'visible'});
 if(!await page.getByText('4 个视频 × 1 个账号 = 4 次上传',{exact:true}).isVisible())throw new Error('Upload confirmation did not describe actual files');
 await page.locator('[data-action="upload-close"]').first().click();
 await page.setViewportSize({width:1024,height:768});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Minimum desktop size overflow');
 if(errors.length)throw new Error(errors.join('\n'));
 fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({pages:results,errors,scan:true,pipeline:true,videoPlayback:true,uploadConfirmation:true,externalUploadExecuted:false,minimumDesktopWidth:1024},null,2));
 await browser.close();console.log('UI acceptance passed: 11 pages, scan, pipeline, video playback, upload review, 1024px layout. No external upload.');
})().catch(e=>{console.error(e);process.exitCode=1;});
