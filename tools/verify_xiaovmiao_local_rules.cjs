const assert=require('node:assert/strict');
const {normalizeProfile,allowsProfileRequest,explainFeatureError}=require('../engines/xiaovmiao-local-accounts');
const uid='9000000000000000001';
assert.equal(normalizeProfile({status_code:0,user_info:{uid,nickname:'fixture'}}).uid,uid);
assert.equal(normalizeProfile({status_code:8,user_info:{uid,nickname:'fixture'}}),null);
assert.equal(normalizeProfile({status_code:0,user_info:{uid:'0',nickname:'visitor'}}),null);
assert.equal(normalizeProfile({status_code:0,user_info:{uid:9000000000000000001,nickname:'rounded'}}),null);
assert.equal(normalizeProfile({data:{user:{user_id:uid,nickname:'fixture',avatar_url:'http://invalid.example/avatar'}}}).avatar,'');
assert.equal(normalizeProfile({user_info:{uid,nickname:'fixture',avatar_thumb:{url_list:['https://p3.douyinpic.com/avatar']}}}).avatar,'https://p3.douyinpic.com/avatar');
assert.equal(allowsProfileRequest('https://creator.douyin.com/web/api/media/user/info/'),true);
assert.equal(allowsProfileRequest({url:'https://creator.douyin.com/web/api/media/user/info/?source=web'}),true);
assert.equal(allowsProfileRequest('https://creator.douyin.com.evil.example/web/api/media/user/info/'),false);
assert.equal(allowsProfileRequest('http://creator.douyin.com/web/api/media/user/info/'),false);
assert.equal(allowsProfileRequest('https://creator.douyin.com/web/api/media/user/info/elsewhere'),false);
assert.equal(allowsProfileRequest('https://baoteyun.com/'),false);
const missingUser=new TypeError("Cannot read properties of null (reading 'is_vip')");
const explained=explainFeatureError(missingUser,'CommentManager.getCommentPostList',false);
assert.equal(explained.code,'LOCAL_SOFTWARE_LOGIN_REQUIRED');
assert.match(explained.message,/小v猫软件账号/);
assert.equal(explainFeatureError(missingUser,'CommentManager.getCommentPostList',true),missingUser);
assert.equal(explainFeatureError(missingUser,'Other.method',false),missingUser);
const denied=Error('Membership required');
assert.equal(explainFeatureError(denied,'CommentManager.getCommentPostList',false),denied);
console.log('XIAOVMIAO_LOCAL_ACCOUNT_RULES_OK');
